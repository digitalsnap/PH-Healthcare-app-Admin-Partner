-- 0009: row-level security.
--
-- RLS is enabled on every table, so nothing is reachable with the public key
-- unless a policy below allows it. The service role bypasses RLS and is used
-- only by server code; it is never shipped to a client.
--
-- Patient data (patient_profile, care_circle, circle_membership, appointment,
-- appointment_event, access_log):
--   * Access by another person goes through has_circle_consent(), which
--     requires the patient's recorded, unrevoked consent. A membership or
--     booked_by relationship alone grants nothing.
--   * There is deliberately NO blanket policy for admin/staff. Internal lookups
--     of patient data go through server endpoints that write to access_log.
--   * There are no client write policies. Writes go through server endpoints
--     (which validate, apply consent rules and log access).

alter table public.app_user enable row level security;
alter table public.location enable row level security;
alter table public.organization enable row level security;
alter table public.facility enable row level security;
alter table public.practitioner enable row level security;
alter table public.practitioner_facility enable row level security;
alter table public.service enable row level security;
alter table public.service_prep enable row level security;
alter table public.price_item enable row level security;
alter table public.coverage_program enable row level security;
alter table public.accreditation enable row level security;
alter table public.patient_profile enable row level security;
alter table public.care_circle enable row level security;
alter table public.circle_membership enable row level security;
alter table public.access_log enable row level security;
alter table public.schedule enable row level security;
alter table public.availability_rule enable row level security;
alter table public.schedule_exception enable row level security;
alter table public.slot enable row level security;
alter table public.appointment enable row level security;
alter table public.appointment_event enable row level security;
alter table public.verification_task enable row level security;
