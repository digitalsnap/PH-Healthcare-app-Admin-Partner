-- ---------------------------------------------------------------------------
-- Accounts
-- ---------------------------------------------------------------------------
create policy app_user_select_own_or_staff on public.app_user
  for select to authenticated
  using (id = (select auth.uid()) or (select public.is_staff()));

-- Only admins assign roles or deactivate accounts.
create policy app_user_admin_write on public.app_user
  for all to authenticated
  using ((select public.current_app_role()) = 'admin')
  with check ((select public.current_app_role()) = 'admin');

-- ---------------------------------------------------------------------------
-- Supply, coverage and admin tables: internal team only for now. Doctor and
-- provider-portal policies arrive with those surfaces; public read access
-- arrives with the public website.
-- ---------------------------------------------------------------------------
do $$
declare
  t text;
begin
  foreach t in array array[
    'location', 'organization', 'facility', 'practitioner', 'practitioner_facility',
    'service', 'service_prep', 'price_item', 'coverage_program', 'accreditation',
    'schedule', 'availability_rule', 'schedule_exception',
    'verification_task', 'data_source_import'
  ]
  loop
    execute format(
      'create policy staff_all on public.%I for all to authenticated '
      'using ((select public.is_staff())) with check ((select public.is_staff()))',
      t
    );
  end loop;
end;
$$;

-- A doctor reads their own practitioner row (PRC status is set by admin).
create policy practitioner_select_own on public.practitioner
  for select to authenticated
  using (app_user_id = (select auth.uid()));

-- Slots are generated by the server; nobody posts them, staff included.
create policy slot_staff_select on public.slot
  for select to authenticated
  using ((select public.is_staff()));

-- ---------------------------------------------------------------------------
-- Patient data
-- ---------------------------------------------------------------------------

-- The patient, or a care manager with recorded consent. Payers and viewers get
-- only what the server chooses to send them (receipts, visit updates).
create policy patient_profile_select on public.patient_profile
  for select to authenticated
  using (
    app_user_id = (select auth.uid())
    or public.has_circle_consent(id, array['care_manager']::public.circle_role[])
  );

create policy care_circle_select on public.care_circle
  for select to authenticated
  using (
    public.is_patient_self(patient_id)
    or public.has_circle_consent(
      patient_id, array['care_manager', 'payer', 'viewer']::public.circle_role[]
    )
  );

-- A member sees their own membership (including a pending invitation); the
-- patient sees everyone in their circle.
create policy circle_membership_select on public.circle_membership
  for select to authenticated
  using (
    member_user_id = (select auth.uid())
    or exists (
      select 1 from public.care_circle c
      where c.id = circle_id and public.is_patient_self(c.patient_id)
    )
  );

-- The patient, a consented care manager, or the practitioner the appointment
-- is with. booked_by on its own grants nothing.
create policy appointment_select on public.appointment
  for select to authenticated
  using (
    public.is_patient_self(patient_id)
    or public.has_circle_consent(patient_id, array['care_manager']::public.circle_role[])
    or exists (
      select 1 from public.practitioner p
      where p.id = practitioner_id and p.app_user_id = (select auth.uid())
    )
  );

-- Visible exactly when the appointment is (the subquery runs under the
-- caller's own appointment policy).
create policy appointment_event_select on public.appointment_event
  for select to authenticated
  using (exists (select 1 from public.appointment a where a.id = appointment_id));

-- The patient sees who accessed their data; admins review the log.
create policy access_log_select on public.access_log
  for select to authenticated
  using (
    public.is_patient_self(subject_patient_id)
    or (select public.current_app_role()) = 'admin'
  );
